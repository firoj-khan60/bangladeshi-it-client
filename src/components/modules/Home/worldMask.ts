/** Decodes the mask into one byte per pixel: 255 = land, 0 = water. */
export function decodeWorldMask(): Uint8Array {
  const bin = atob(WORLD_MASK_RLE);
  const out = new Uint8Array(WORLD_MASK_WIDTH * WORLD_MASK_HEIGHT);
  let i = 0;
  const readVarint = () => {
    let n = 0;
    let shift = 0;
    for (;;) {
      const c = bin.charCodeAt(i++);
      n |= (c & 0x7f) << shift;
      if (!(c & 0x80)) return n;
      shift += 7;
    }
  };
  for (let row = 0; row < WORLD_MASK_HEIGHT; row++) {
    let x = 0;
    let land = false;
    while (x < WORLD_MASK_WIDTH) {
      const run = readVarint();
      if (land) out.fill(255, row * WORLD_MASK_WIDTH + x, row * WORLD_MASK_WIDTH + x + run);
      x += run;
      land = !land;
    }
  }
  return out;
}
